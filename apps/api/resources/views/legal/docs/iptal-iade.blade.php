<div class="ys-b">
    <h2 class="h3">Cayma Hakkı Süresi</h2>
    <p class="gvd">Sipario, 30 (otuz) gün ücretsiz deneme sonunda Alıcı'nın açık onayı ile ödeme alınıp derhal aktive edilen dijital bir hizmettir. Mesafeli Sözleşmeler Yönetmeliği m.15/1-ğ uyarınca, tüketicinin onayıyla ifasına derhal başlanan bu nitelikteki hizmetlerde cayma hakkı kullanılamayabilir; Alıcı bu hususu ödeme adımında ayrıca onaylar. Bu istisnanın kesin kapsamı ve olası ayrık durumlar (ör. ödeme sonrası hizmete hiç erişilmemesi) için avukat onayı beklenmektedir.</p>
</div>

<div class="ys-b">
    <h2 class="h3">İade Süreci</h2>
    <p class="gvd">Cayma hakkının istisna kapsamında olmadığı veya Satıcı'nın takdirine bağlı olarak iade kararı verildiği durumlarda, Alıcı iade talebini destek kanalı üzerinden Satıcı'ya iletir. Talep incelenip onaylandığında bedel iadesi, ödemenin alındığı iyzico altyapısı üzerinden aynı ödeme yöntemine yapılır. [İade talebi için azami değerlendirme süresi ve iade süresi — doldurulacak.]</p>
</div>

<div class="ys-b">
    <h2 class="h3">Abonelik İptali</h2>
    <p class="gvd">Alıcı, aboneliğini dilediği zaman destek kanalı üzerinden iptal edebilir. İptal, cari 365 günlük abonelik döneminin sonunda geçerli olur; dönem içinde kullanılmayan süre için orantılı iade yapılıp yapılmayacağı ve otomatik yenileme koşulları [doldurulacak]. Abonelik iptal edilse veya süresi dolsa dahi Alıcı'ya ait veriler silinmez; Türkiye'deki sunucuda saklanmaya devam eder ve Alıcı, destek kanalı üzerinden her zaman verilerinin dışa aktarımını (export) talep edebilir.</p>
</div>

<div class="ys-b">
    <h2 class="h3">İtiraz ve Başvuru</h2>
    <p class="gvd">Alıcı, iptal/iade talebine ilişkin itirazlarını Ticaret Bakanlığı'nca ilan edilen parasal sınırlar dahilinde yerleşim yerindeki Tüketici Hakem Heyetleri'ne veya Tüketici Mahkemeleri'ne iletebilir. [Yetkili başvuru mercii detayları — doldurulacak.]</p>
</div>
