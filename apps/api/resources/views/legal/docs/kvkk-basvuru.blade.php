<div class="ys-b">
    <h2 class="h3">Bu sayfa ne işe yarar?</h2>
    <p class="gvd">6698 sayılı KVKK m.11, kişisel verilerinizle ilgili birtakım haklar tanır: verinizin işlenip işlenmediğini öğrenme, bilgi isteme, yanlışsa düzelttirme, şartları varsa sildirme ve zararınızın giderilmesini talep etme. Bu sayfa, o hakları Sipario'ya karşı nasıl kullanacağınızı anlatır.</p>
    <p class="gvd">Başvurunuz <strong>en geç 30 gün içinde</strong> sonuçlandırılır ve kural olarak <strong>ücretsizdir</strong>.</p>
</div>

<div class="ys-b">
    <h2 class="h3">1. Önce: doğru muhatap biz miyiz?</h2>
    <p class="gvd">Bu ayrım önemlidir, çünkü yanlış muhataba yapılan başvuru sizi zaman kaybettirir.</p>
    <ul class="ys-liste">
        <li><b>Sipario'ya abone bir işletme veya çalışanıysanız</b> ve <em>kendi</em> hesap verileriniz hakkında talepte bulunuyorsanız, doğru muhatap <strong>Sipario'dur</strong>. Aşağıdaki yolu izleyin.</li>
        <li><b>Sipario kullanan bir işletmenin müşterisiyseniz</b> (ör. su siparişi verdiğiniz bayi sizi sisteme kaydetmişse), o veriler bakımından veri sorumlusu <strong>bayinin kendisidir</strong>, Sipario değil. Talebinizi doğrudan o işletmeye iletmelisiniz. Sipario, o işletmenin talimatıyla çalışan "veri işleyen"dir ve verinizi kendi kararıyla silemez veya paylaşamaz.</li>
    </ul>
    <p class="gvd">İkinci gruptaysanız ve işletmeye ulaşamıyorsanız yine de bize yazabilirsiniz: talebinizi ilgili işletmeye yönlendirir ve size bilgi veririz.</p>
</div>

<div class="ys-b">
    <h2 class="h3">2. Başvuruda bulunması zorunlu bilgiler</h2>
    <p class="gvd">Veri Sorumlusuna Başvuru Usul ve Esasları Hakkında Tebliğ m.5 uyarınca başvurunuzda şunlar bulunmalıdır:</p>
    <ul class="ys-liste">
        <li>Ad, soyad ve yazılı başvurularda imza,</li>
        <li>Türkiye Cumhuriyeti vatandaşları için T.C. kimlik numarası; yabancılar için uyruk, pasaport numarası veya varsa kimlik numarası,</li>
        <li>Tebligata esas yerleşim yeri veya iş yeri adresi,</li>
        <li>Varsa bildirime esas elektronik posta adresi, telefon ve faks numarası,</li>
        <li><strong>Talep konusu</strong> — ne istediğinizi açıkça yazın.</li>
    </ul>
    <p class="gvd">Talebinize konu bilgi ve belgeleri (ör. yanlış olduğunu düşündüğünüz kaydın ekran görüntüsü) eklerseniz süreç hızlanır. Sipario abonesiyseniz <strong>firma kodunuzu</strong> belirtmeniz kimliğinizin doğrulanmasını kolaylaştırır.</p>
</div>

