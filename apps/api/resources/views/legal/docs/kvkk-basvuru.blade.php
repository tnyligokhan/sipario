<div class="ys-b">
    <h2 class="h3">4. Süre ve ücret</h2>
    <p class="gvd">Başvurunuz, bize ulaştığı tarihten itibaren <strong>en geç 30 gün</strong> içinde sonuçlandırılır ve cevabımız size yazılı olarak veya elektronik ortamda bildirilir (KVKK m.13/2).</p>
    <p class="gvd">Başvurunuz kural olarak <strong>ücretsizdir</strong>. İşlemin ayrıca bir maliyet gerektirmesi hâlinde (ör. cevabın basılı olarak on sayfayı aşan şekilde gönderilmesi veya kayıt ortamında verilmesi), Kişisel Verileri Koruma Kurulu'nca belirlenen tarifedeki ücret alınabilir. Hatanın bizden kaynaklandığı hâllerde alınan ücret iade edilir.</p>
</div>

<div class="ys-b">
    <h2 class="h3">5. Kimlik doğrulama</h2>
    <p class="gvd">Talebinizi karşılamadan önce kimliğinizi doğrularız. Bu bir engelleme değil, korumadır: doğrulama yapılmadan verilen bir cevap, sizin verinizi başka birine teslim etmek anlamına gelebilir.</p>
    <p class="gvd">Doğrulama; kayıtlı e-posta adresinizden gelen başvurularda o adresin teyidiyle, diğer hâllerde kimlik belgesi ile yapılır. Kimlik belgesi kopyaları yalnız doğrulama amacıyla kullanılır ve doğrulamanın ardından imha edilir.</p>
</div>

<div class="ys-b">
    <h2 class="h3">6. Başvurunuz reddedilirse</h2>
    <p class="gvd">Başvurunuzun reddedilmesi, verdiğimiz cevabı yetersiz bulmanız veya süresinde cevap verilmemesi hâlinde; cevabı öğrendiğiniz tarihten itibaren <strong>30 gün</strong> ve her hâlde başvuru tarihinden itibaren <strong>60 gün</strong> içinde <strong>Kişisel Verileri Koruma Kurulu'na</strong> şikâyette bulunabilirsiniz (KVKK m.14).</p>
    <p class="gvd">Kurul'a başvuru, veri sorumlusuna başvuru yolu tüketilmeden yapılamaz. Bu nedenle önce bize yazmanız gerekir.</p>
</div>

